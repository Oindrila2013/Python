DROP TABLE IF EXISTS SALES;
CREATE TABLE IF NOT EXISTS SALES (
    ID INT PRIMARY KEY,
    ITEM VARCHAR(50),
    CATEGORY VARCHAR(50),
    PRICE INT,
    QUANTITY INT,
    TOTAL INT
);

