SELECT SUM(TOTAL) AS SHOP_INCOME FROM SALES;

SELECT MIN(TOTAL) AS SMALLEST_SALE FROM SALES;

SELECT MAX(TOTAL) AS BIGGEST_SALE FROM SALES;

